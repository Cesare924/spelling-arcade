// Packs games-web/shell.html + games-web/games.js into one offline page,
// saved as a string in src/games/gameHtml.ts. Run after editing a game:
//   node scripts/pack-games.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const shell = readFileSync(join(root, 'games-web/shell.html'), 'utf8');
const games = readFileSync(join(root, 'games-web/games.js'), 'utf8');
if (!shell.includes('/*__GAMES__*/')) throw new Error('shell.html is missing the /*__GAMES__*/ marker');
const html = shell.replace('/*__GAMES__*/', () => games.replace(/<\/script/gi, '<\\/script'));
writeFileSync(join(root, 'games-web/game.html'), html);
writeFileSync(join(root, 'src/games/gameHtml.ts'),
  '// Generated by scripts/pack-games.mjs. Do not edit by hand.\n' +
  `export const GAME_HTML = ${JSON.stringify(html)};\n`);
console.log(`Packed ${Math.round(html.length / 1024)} KB of game code.`);
